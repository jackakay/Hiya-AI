import { PROTOCOL_VERSION, type BugEvent } from "@voice-bug/shared";
import { Transport } from "./transport";
import { captureClicks } from "./capture/clicks";
import { captureConsole } from "./capture/console";
import { captureErrors } from "./capture/errors";
import { captureNetwork } from "./capture/network";
import { ActionTracker, debugIdDecorator } from "./capture/correlation";
import { VoiceOverlay } from "./voice/overlay";
import { captureScreenshots } from "./capture/screenshots";

export type InitOptions = {
  /** Port of the extension's capture hub (from .voice-bug/session.json). */
  port: number;
  /** Session token generated by the extension. */
  token: string;
  /** Show the voice overlay (default true). */
  voice?: boolean;
  /** Take masked screenshots after clicks and errors (default true). */
  screenshots?: boolean;
};

export type VoiceBugHandle = { stop(): void };

declare global {
  interface Window {
    __voiceBug?: VoiceBugHandle;
  }
}

/** True for URLs pointing at the capture hub itself, which must never be recorded. */
export function isHubUrl(url: string, port: number): boolean {
  try {
    const u = new URL(url);
    return ["127.0.0.1", "localhost", "[::1]"].includes(u.hostname) && Number(u.port) === port;
  } catch {
    return false;
  }
}

/** Starts capturing and streaming events to the VS Code extension. Dev-only. */
export function init(options: InitOptions): VoiceBugHandle {
  if (window.__voiceBug) return window.__voiceBug;

  const url = `ws://127.0.0.1:${options.port}/?token=${encodeURIComponent(options.token)}`;
  let overlay: VoiceOverlay | undefined;
  const transport = new Transport(
    url,
    () => transport.send({ kind: "hello", protocol: PROTOCOL_VERSION, url: location.href, userAgent: navigator.userAgent }),
    (msg) => overlay?.receive(msg),
  );
  const emit = (event: BugEvent) => transport.send({ kind: "event", event });

  const actions = new ActionTracker();
  const stops = [
    captureConsole(emit),
    captureErrors(emit),
    captureNetwork(emit, {
      // The hub and the overlay's own voice assets aren't the app's traffic.
      ignoreUrl: (u) => isHubUrl(u, options.port) || u.includes("/__voice-bug/"),
      // X-Debug-Id on same-origin requests, so server logs link back (milestone 4).
      decorateRequest: debugIdDecorator(() => location.origin, actions),
    }),
    captureClicks(emit, actions),
  ];

  if (options.screenshots !== false) stops.push(captureScreenshots((msg) => transport.send(msg)));

  if (options.voice !== false) {
    overlay = new VoiceOverlay({
      send: (msg) => transport.send(msg),
      connected: () => transport.connected(),
      // onnxruntime + the VAD model load only when the mic is first turned on.
      createVad: async (cb, audioContext) => (await import("./voice/vad")).createVad(cb, audioContext),
    });
    const o = overlay;
    stops.push(() => o.destroy());
  }

  const handle: VoiceBugHandle = {
    stop() {
      for (const stop of stops) stop();
      transport.close();
      delete window.__voiceBug;
    },
  };
  window.__voiceBug = handle;
  return handle;
}
